public class NumberChoice {

    public static void main(String[] args) {

        int x = 1;

        if (x == 1) {

            System.out.println("Hi");

        } else if (x == 2) {

            System.out.println("Hello");

        } else if (x == 3) {

            System.out.println("Good Bye");

        } else {

            System.out.println("Wrong Input");

        }

    }
}